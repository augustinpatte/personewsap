#!/usr/bin/env node
/**
 * Generate the learning catalog seed migration from content/learning-paths/v1.
 *
 * The JSON files stay the single source of truth for the curriculum. This
 * script mirrors them into public.learning_catalog_domains so the mobile app
 * can resolve the next step on demand (self-paced sessions) without bundling
 * 575 KB of curriculum into the app binary.
 *
 * Re-run after editing the catalog:
 *   node scripts/learning-catalog-sql.mjs > supabase/migrations/<ts>_learning_catalog_seed.sql
 */

import { readdirSync, readFileSync } from "node:fs";
import path from "node:path";

const CATALOG_DIR = path.join(process.cwd(), "content", "learning-paths", "v1");
const TAG = "$catalog$";

function loadDomains() {
  return readdirSync(CATALOG_DIR)
    .filter((file) => file.endsWith(".json") && file !== "catalog-index.json")
    .sort()
    .map((file) => {
      const payload = JSON.parse(readFileSync(path.join(CATALOG_DIR, file), "utf8"));

      if (!payload.domain_id || !Array.isArray(payload.steps)) {
        throw new Error(`${file} is not a catalog domain file.`);
      }

      return payload;
    });
}

function main() {
  const domains = loadDomains();
  const lines = [
    "-- GENERATED by scripts/learning-catalog-sql.mjs — do not edit by hand.",
    "-- Mirrors content/learning-paths/v1 into the database so the app can",
    "-- resolve the next learning step on demand. Data only; additive.",
    ""
  ];

  for (const domain of domains) {
    const json = JSON.stringify({ version: domain.version, steps: domain.steps });

    if (json.includes(TAG)) {
      throw new Error(`Catalog for ${domain.domain_id} collides with the SQL quoting tag.`);
    }

    lines.push(
      "INSERT INTO public.learning_catalog_domains (domain_id, version, payload)",
      `VALUES (${TAG}${domain.domain_id}${TAG}, ${TAG}${domain.version}${TAG}, ${TAG}${json}${TAG}::jsonb)`,
      "ON CONFLICT (domain_id) DO UPDATE",
      "SET version = EXCLUDED.version, payload = EXCLUDED.payload, updated_at = now();",
      ""
    );
  }

  process.stdout.write(lines.join("\n"));
}

main();
